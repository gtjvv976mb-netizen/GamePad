// Writes the compiled ABI to the front-end as a viem-typed const: ../src/web3/storeAbi.ts
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { ROOT } from "./build.mjs";
import { loadArtifact } from "./deploy.mjs";

const target = join(ROOT, "..", "src", "web3", "storeAbi.ts");
const { abi, compiler } = loadArtifact();

const ts = `// Generated by contracts/scripts/export-abi.mjs (${compiler}). Do not edit by hand:
// change contracts/src/GamePadStore.sol, then run \`cd contracts && npm run export-abi\`.
export const storeAbi = ${JSON.stringify(abi, null, 2)} as const;
`;

mkdirSync(dirname(target), { recursive: true });
writeFileSync(target, ts);
console.log(`Wrote ${abi.length} ABI entries to ${relative(process.cwd(), target)}`);
